def საშუალო(რიცხვები):
    if len(რიცხვები) == 0:
        return 0
        
    ჯამი = 0
    for რიცხვი in რიცხვები:
        ჯამი = ჯამი + რიცხვი
        
    საშუალო_მნიშვნელობა = ჯამი / len(რიცხვები)
    return საშუალო_მნიშვნელობა



print(საშუალო([3, 7, 1, 9]))        
print(საშუალო([10, 20, 30]))         
print(საშუალო([5]))                   
print(საშუალო([]))                    

