def უდიდესი_რიცხვი(რიცხვები):
    უდიდესი = რიცხვები[0]         
    
    for რიცხვი in რიცხვები:
        if რიცხვი > უდიდესი:
            უდიდესი = რიცხვი
            
    return უდიდესი



სია = [3, 7, 1, 9]
პასუხი = უდიდესი_რიცხვი(სია)
print("ყველაზე დიდი რიცხვია:", პასუხი)    



