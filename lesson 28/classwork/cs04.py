#  მომხმარებელს შემოაყვანინე ასაკი, თუ ასაკინ < 18-ზე -> "შენ ხარ არასრულწლოვანი", თუ ასაკი 18 და 64 შორისაა -> 
# "შენ ხარ სრულწლოვანი", თუ ასაკი > 65-ზე -> "შენ ხარ პენსიონერი"

age = int(input("შეიყვანე შენი ასაკი: "))

if age < 18:
    print("შენ ხარ არასრულწლოვანი")
elif 18 <= age <= 64:
    print("შენ ხარ სრულწლოვანი")
else:  # age >= 65
    print("შენ ხარ პენსიონერი")